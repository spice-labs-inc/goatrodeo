def main() -> int:
    """Run synthetic generators. Optional first argument restricts to one
    category — used by per-category `generate.sh` wrappers (see
    `test_data/certificates/{category}/synthetic/generate.sh`).
    """
    # Categories accepted as the optional first arg
    CATEGORY_ALIASES = {
        "x509": "x509",
        "ssh": "ssh",
        "pgp": "pgp",
        "crls": "crls",
        "keystores": "keystores",
        "private-keys": "private-keys",
        "edge-cases": "edge-cases",
        "pem-bundles": "pem-bundles",  # produced by gen_x509_synthetic
    }
    only = None
    if len(sys.argv) > 1:
        if sys.argv[1] not in CATEGORY_ALIASES:
            print(f"unknown category: {sys.argv[1]}; valid: "
                  f"{sorted(CATEGORY_ALIASES.keys())}", file=sys.stderr)
            return 2
        only = CATEGORY_ALIASES[sys.argv[1]]

    def _run_if(name: str, fn):
        if only is None or only == name:
            return fn()
        return []

    # Note: gen_x509_synthetic also produces a PEM-bundles fixture
    # (the synthetic 2-cert chain). When only="pem-bundles" we need the
    # x509 generator to run too.
    x509_rows = _run_if("x509", gen_x509_synthetic) if only != "pem-bundles" \
        else gen_x509_synthetic()
    ssh_rows = _run_if("ssh", gen_ssh_synthetic)
    github_rows = _run_if("ssh", gen_github_ssh)
    pgp_rows = _run_if("pgp", gen_pgp_synthetic)
    pk_rows = _run_if("private-keys", gen_private_keys)
    crl_rows = _run_if("crls", gen_crls)
    ks_rows = _run_if("keystores", gen_keystores)
    edge_rows = _run_if("edge-cases", gen_edge_cases)

    # Append rows into each SOURCES.md
    def _append_table(path: Path, header: str, rows: list[str]) -> None:
        if not rows:
            return
        _append(path, "\n" + header + "\n\n"
                "| Filename | Source | Retrieved | SHA-256 |\n"
                "|---|---|---|---|\n" + "\n".join(rows) + "\n")

    _append_table(CORPUS_ROOT / "x509" / "SOURCES.md",
                  "## Synthetic X.509 fixtures", x509_rows)
    _append_table(CORPUS_ROOT / "ssh" / "SOURCES.md",
                  "## Synthetic SSH fixtures", ssh_rows)
    _append_table(CORPUS_ROOT / "ssh" / "SOURCES.md",
                  "## GitHub .keys fixtures (real-world pubkeys)", github_rows)
    _append_table(CORPUS_ROOT / "pgp" / "SOURCES.md",
                  "## Synthetic PGP fixtures", pgp_rows)
    _append_table(CORPUS_ROOT / "private-keys" / "SOURCES.md",
                  "## Synthetic private-key fixtures", pk_rows)
