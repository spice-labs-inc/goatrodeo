def gen_x509_synthetic() -> list[str]:
    """Produce synthetic X.509 fixtures. Returns SOURCES.md row strings."""
    rows: list[str] = []
    dir_ = CORPUS_ROOT / "x509" / "synthetic"

    # 1. Ed25519 self-signed (the canonical alg=ed25519 coverage fixture)
    now = datetime(2026, 1, 1, tzinfo=timezone.utc)
    ed_key = ed25519.Ed25519PrivateKey.generate()
    ed_cert = _make_x509_selfsigned(
        ed_key, "GoatRodeo Test Ed25519", now, now + timedelta(days=3650),
    )
    _write_cert_fixture(
        dir_, "ed25519-selfsigned", ed_cert,
        description="Goat Rodeo synthetic Ed25519 self-signed CA",
        source=SOURCE_GENERATED,
    )
    sha = _sha256(ed_cert.public_bytes(serialization.Encoding.PEM))
    rows.append(f"| synthetic/ed25519-selfsigned.pem | {SOURCE_GENERATED} | {TODAY} | sha256:{sha} |")

    # DER re-encoding of the same cert — covers the DER-encoding coverage cell
    _write_cert_fixture(
        dir_, "ed25519-selfsigned-der", ed_cert,
        description="Goat Rodeo synthetic Ed25519 self-signed CA (DER)",
        source=SOURCE_GENERATED, der=True,
    )
    sha = _sha256(ed_cert.public_bytes(serialization.Encoding.DER))
    rows.append(f"| synthetic/ed25519-selfsigned-der.der | {SOURCE_GENERATED} | {TODAY} | sha256:{sha} |")

    # 2. ECDSA P-256 self-signed
    ec256_key = ec.generate_private_key(ec.SECP256R1())
    ec256_cert = _make_x509_selfsigned(
        ec256_key, "GoatRodeo Test EC P-256", now, now + timedelta(days=3650),
        sig_hash=hashes.SHA256(),
    )
    _write_cert_fixture(
        dir_, "ec-p256-selfsigned", ec256_cert,
        description="Goat Rodeo synthetic ECDSA P-256 self-signed",
        source=SOURCE_GENERATED,
    )
    sha = _sha256(ec256_cert.public_bytes(serialization.Encoding.PEM))
    rows.append(f"| synthetic/ec-p256-selfsigned.pem | {SOURCE_GENERATED} | {TODAY} | sha256:{sha} |")

    # 3. ECDSA P-384 self-signed
    ec384_key = ec.generate_private_key(ec.SECP384R1())
    ec384_cert = _make_x509_selfsigned(
        ec384_key, "GoatRodeo Test EC P-384", now, now + timedelta(days=3650),
        sig_hash=hashes.SHA384(),
    )
    _write_cert_fixture(
        dir_, "ec-p384-selfsigned", ec384_cert,
        description="Goat Rodeo synthetic ECDSA P-384 self-signed",
        source=SOURCE_GENERATED,
    )
    sha = _sha256(ec384_cert.public_bytes(serialization.Encoding.PEM))
    rows.append(f"| synthetic/ec-p384-selfsigned.pem | {SOURCE_GENERATED} | {TODAY} | sha256:{sha} |")

    # 4. RSA-2048 self-signed (small size; Mozilla has 4096 mostly)
    rsa2048_key = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    rsa2048_cert = _make_x509_selfsigned(
        rsa2048_key, "GoatRodeo Test RSA-2048", now, now + timedelta(days=3650),
    )
    _write_cert_fixture(
        dir_, "rsa-2048-selfsigned", rsa2048_cert,
        description="Goat Rodeo synthetic RSA-2048 self-signed",
        source=SOURCE_GENERATED,
    )
    sha = _sha256(rsa2048_cert.public_bytes(serialization.Encoding.PEM))
    rows.append(f"| synthetic/rsa-2048-selfsigned.pem | {SOURCE_GENERATED} | {TODAY} | sha256:{sha} |")

    # 5. SHA-1 signed RSA (for deprecated-algo coverage).
    # The `cryptography` library refuses to sign with SHA-1 for safety;
    # we use the openssl CLI instead, which still permits it.
    with tempfile.TemporaryDirectory() as td:
        k = os.path.join(td, "sha1.key")
        c = os.path.join(td, "sha1.pem")
        _sh(["openssl", "genpkey", "-algorithm", "RSA",
             "-pkeyopt", "rsa_keygen_bits:2048", "-out", k])
        _sh(["openssl", "req", "-new", "-x509", "-key", k,
             "-subj", "/CN=GoatRodeo Test SHA1-legacy/O=Goat Rodeo Test/C=US",
             "-days", "3650",
             "-sha1",
             "-out", c])
        sha1_pem_bytes = Path(c).read_bytes()
        sha1_cert = x509.load_pem_x509_certificate(sha1_pem_bytes)
    _write_cert_fixture(
        dir_, "rsa-2048-sha1-selfsigned", sha1_cert,
        description="Goat Rodeo synthetic RSA-2048 SHA-1-signed (deprecated)",
        source=SOURCE_GENERATED,
    )
    sha = _sha256(sha1_cert.public_bytes(serialization.Encoding.PEM))
    rows.append(f"| synthetic/rsa-2048-sha1-selfsigned.pem | {SOURCE_GENERATED} | {TODAY} | sha256:{sha} |")

    # 6. Non-self-signed intermediate (signed by rsa2048_cert)
    int_key, int_cert = _make_x509_intermediate(
        "GoatRodeo Test Intermediate CA",
        rsa2048_key, rsa2048_cert,
        now, now + timedelta(days=1825),
    )
    _write_cert_fixture(
        dir_, "rsa-2048-intermediate", int_cert,
        description="Goat Rodeo synthetic intermediate signed by RSA-2048 root",
        source=SOURCE_GENERATED,
    )
    sha = _sha256(int_cert.public_bytes(serialization.Encoding.PEM))
    rows.append(f"| synthetic/rsa-2048-intermediate.pem | {SOURCE_GENERATED} | {TODAY} | sha256:{sha} |")

    # Also produce a small PEM bundle containing root + intermediate
    bundle_dir = CORPUS_ROOT / "pem-bundles" / "synthetic"
    bundle_pem = (
        rsa2048_cert.public_bytes(serialization.Encoding.PEM)
        + int_cert.public_bytes(serialization.Encoding.PEM)
    )
    _write(bundle_dir / "goatrodeo-test-chain.pem", bundle_pem)
    sha_bundle = _sha256(bundle_pem)
    # Sidecar for the bundle — two certs; pURLs deferred to Phase 4
    bundle_sidecar = {
        "description": "Goat Rodeo synthetic 2-cert PEM chain (RSA-2048 root + intermediate)",
        "source": SOURCE_GENERATED,
        "retrievedAt": TODAY,
        "itemCount": 1,
        "mimeTypes": {
            "mustContain": ["application/x-pem-file", "application/x-pem-bundle"]
        },
        "purls": {
            "mustContain": [
                "<computed: 2 spki + 2 cert pURLs in Phase 4>"
            ]
        },
        "metadata": {
            "mustContain": {
                "Certificates:KeystoreType": "pem-bundle",
                "Certificates:EntryCount": "2",
                "Certificates:CertCount": "2",
                "Certificates:KeyEntryCount": "0",
            }
        },
        "forbiddenMetadataKeys": [],
        "forbiddenMetadataPatterns": list(cert_sidecar.FORBIDDEN_PATTERNS_DEFAULT),
    }
    cert_sidecar.write_sidecar(
        str(bundle_dir / "goatrodeo-test-chain.pem.expected.json"),
        bundle_sidecar,
    )

    return rows + [
        f"| (pem-bundles/synthetic/goatrodeo-test-chain.pem) | {SOURCE_GENERATED} | {TODAY} | sha256:{sha_bundle} |"
    ]


def _hand_sidecar(
    dir_: Path, fixture_name: str,
    *,
    description: str, source: str, item_count: int = 1,
    mime_types: list[str], purls: list[str],
    mime_types_not: list[str] | None = None,
    purls_not: list[str] | None = None,
    metadata: dict[str, str] | None = None,
    forbidden_keys: list[str] | None = None,
) -> None:
    sc = {
        "description": description,
        "source": source,
        "retrievedAt": TODAY,
        "itemCount": item_count,
        "mimeTypes": {"mustContain": mime_types},
        "purls": {"mustContain": purls},
        "metadata": {"mustContain": metadata or {}},
        "forbiddenMetadataKeys": forbidden_keys or [],
        "forbiddenMetadataPatterns": list(cert_sidecar.FORBIDDEN_PATTERNS_DEFAULT),
    }
    if mime_types_not is not None:
        sc["mimeTypes"]["mustNotContain"] = mime_types_not
    if purls_not is not None:
        sc["purls"]["mustNotContain"] = purls_not
    cert_sidecar.write_sidecar(str(dir_ / f"{fixture_name}.expected.json"), sc)


def gen_ssh_synthetic() -> list[str]:
    """Generate SSH pubkeys and OpenSSH-cert fixtures."""
    rows: list[str] = []
    dir_ = CORPUS_ROOT / "ssh" / "synthetic"
    dir_.mkdir(parents=True, exist_ok=True)

    with tempfile.TemporaryDirectory() as td:
        variants = [
            ("rsa-4096", ["-t", "rsa", "-b", "4096"]),
            ("ed25519", ["-t", "ed25519"]),
            ("ecdsa-nistp256", ["-t", "ecdsa", "-b", "256"]),
            ("ecdsa-nistp384", ["-t", "ecdsa", "-b", "384"]),
        ]
        for name, args in variants:
            priv = os.path.join(td, f"id_{name}")
            _sh(["ssh-keygen", "-q", "-N", "", "-C", f"goatrodeo-{name}@test",
                 "-f", priv] + args)
            pub_bytes = Path(priv + ".pub").read_bytes()
            _write(dir_ / f"{name}-openssh.pub", pub_bytes)
            _hand_sidecar(
                dir_, f"{name}-openssh.pub",
                description=f"SSH public key ({name}) generated for testing",
                source=SOURCE_GENERATED,
                mime_types=["application/x-openssh-public-key"],
                purls=["<computed: pkg:ssh/sha256@... in Phase 5>"],
                metadata={"Certificates:KeyAlgorithm": "<computed in Phase 5>"},
            )
            rows.append(
                f"| synthetic/{name}-openssh.pub | {SOURCE_GENERATED} | {TODAY} | sha256:{_sha256(pub_bytes)} |"
            )
            # Private key NOT committed — this is a pub-key fixture only.

        # OpenSSH CA setup
        ca_ed = os.path.join(td, "ca_ed25519")
        _sh(["ssh-keygen", "-q", "-N", "", "-C", "goatrodeo-ca",
             "-t", "ed25519", "-f", ca_ed])

        # User cert signed by Ed25519 CA, signing an Ed25519 user key
        user_key = os.path.join(td, "user_ed25519")
        _sh(["ssh-keygen", "-q", "-N", "", "-C", "goatrodeo-user",
             "-t", "ed25519", "-f", user_key])
        _sh(["ssh-keygen", "-s", ca_ed,
             "-I", "goatrodeo-test-user",
             "-n", "alice,bob",
             "-V", "+52w",
             f"{user_key}.pub"])
        _write(dir_ / "user-cert-ed25519.pub",
               Path(user_key + "-cert.pub").read_bytes())
        _hand_sidecar(
            dir_, "user-cert-ed25519.pub",
            description="OpenSSH user certificate (Ed25519 user key, Ed25519 CA)",
            source=SOURCE_GENERATED,
            mime_types=["application/x-openssh-certificate"],
            purls=["<computed: pkg:ssh/cert-sha256@... + pkg:ssh/sha256@... in Phase 5>"],
            metadata={
                "Certificates:SshCertType": "user",
                "Certificates:SshCertPrincipals": "alice,bob",
            },
        )
        rows.append(
            f"| synthetic/user-cert-ed25519.pub | {SOURCE_GENERATED} | {TODAY} | sha256:{_sha256(Path(user_key + '-cert.pub').read_bytes())} |"
        )

        # Host cert: RSA-2048 host key signed by Ed25519 CA (cross-algorithm)
        host_key = os.path.join(td, "host_rsa")
        _sh(["ssh-keygen", "-q", "-N", "", "-C", "goatrodeo-host",
             "-t", "rsa", "-b", "2048", "-f", host_key])
        _sh(["ssh-keygen", "-s", ca_ed,
             "-I", "goatrodeo-test-host",
             "-h",
             "-n", "host1.example,host2.example",
             "-V", "+52w",
             f"{host_key}.pub"])
        _write(dir_ / "host-cert-rsa-signed-by-ed25519.pub",
               Path(host_key + "-cert.pub").read_bytes())
        _hand_sidecar(
            dir_, "host-cert-rsa-signed-by-ed25519.pub",
            description="OpenSSH host certificate — RSA-2048 key signed by Ed25519 CA (cross-algorithm)",
            source=SOURCE_GENERATED,
            mime_types=["application/x-openssh-certificate"],
            purls=["<computed in Phase 5>"],
            metadata={
                "Certificates:SshCertType": "host",
                "Certificates:SshCertPrincipals": "host1.example,host2.example",
            },
        )
        rows.append(
            f"| synthetic/host-cert-rsa-signed-by-ed25519.pub | {SOURCE_GENERATED} | {TODAY} | sha256:{_sha256(Path(host_key + '-cert.pub').read_bytes())} |"
        )

    return rows


def gen_github_ssh() -> list[str]:
    """Download a handful of stable GitHub-hosted SSH pubkeys."""
    import urllib.request
    rows: list[str] = []
    dir_ = CORPUS_ROOT / "ssh" / "github"
    dir_.mkdir(parents=True, exist_ok=True)
    # A small, stable set of maintainer accounts known to have public keys
    # that have been stable for years. If a URL 404s or returns empty, we
    # skip silently rather than fail the whole bootstrap.
    accounts = [
        "torvalds", "gvanrossum", "jepler", "dpp", "rcoh",
        "mitchellh", "ry", "pietroalbini", "dwrensha",
    ]
    for acct in accounts:
        url = f"https://github.com/{acct}.keys"
        try:
            with urllib.request.urlopen(url, timeout=10) as r:
                data = r.read()
        except Exception as e:
            print(f"  skip {url}: {e}", file=sys.stderr)
            continue
        if not data.strip():
            print(f"  skip {url}: empty body", file=sys.stderr)
            continue
        # Take only the first key per account to keep stems unique and to
        # avoid depending on a multi-key-per-account order we can't pin.
        first_line = data.splitlines()[0] + b"\n"
        if not first_line.startswith((
            b"ssh-rsa ", b"ssh-ed25519 ", b"ssh-dss ",
            b"ecdsa-sha2-nistp256 ", b"ecdsa-sha2-nistp384 ",
            b"ecdsa-sha2-nistp521 ",
        )):
            print(f"  skip {url}: unrecognized format", file=sys.stderr)
            continue
        fixture = dir_ / f"github-{acct}.pub"
        _write(fixture, first_line)
        _hand_sidecar(
            dir_, f"github-{acct}.pub",
            description=f"Real-world SSH public key — github.com/{acct}",
            source=url,
            mime_types=["application/x-openssh-public-key"],
            purls=["<computed in Phase 5>"],
            metadata={"Certificates:KeyAlgorithm": "<computed in Phase 5>"},
        )
        rows.append(
            f"| github/github-{acct}.pub | {url} | {TODAY} | sha256:{_sha256(first_line)} |"
        )
    return rows


def gen_pgp_synthetic() -> list[str]:
    """Generate v4 RSA and v4 Ed25519 PGP public keys via gpg."""
    rows: list[str] = []
    dir_ = CORPUS_ROOT / "pgp" / "synthetic"
    dir_.mkdir(parents=True, exist_ok=True)

    for kind, algo_block in [
        ("rsa4096", "Key-Type: RSA\nKey-Length: 4096\nKey-Usage: cert,sign"),
        ("ed25519", "Key-Type: EDDSA\nKey-Curve: ed25519\nKey-Usage: cert,sign"),
    ]:
        with tempfile.TemporaryDirectory() as td:
            env = os.environ.copy()
            env["GNUPGHOME"] = td
            # Init gpg silently (creates trustdb etc.)
            subprocess.run(["gpg", "--homedir", td, "--batch", "--list-keys"],
                           check=False, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            params = (
                "%no-protection\n"
                f"{algo_block}\n"
                f"Name-Real: GoatRodeo Test {kind}\n"
                f"Name-Email: goatrodeo-{kind}@test.invalid\n"
                "Expire-Date: 0\n"
                "%commit\n"
            )
            subprocess.run(
                ["gpg", "--homedir", td, "--batch", "--quiet",
                 "--gen-key"],
                input=params.encode(), check=True,
                stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
            )
            # Export the armored public key
            r = subprocess.run(
                ["gpg", "--homedir", td, "--armor", "--export",
                 f"goatrodeo-{kind}@test.invalid"],
                check=True, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL,
            )
            pub = r.stdout
        fixture = dir_ / f"v4-{kind}-pub.asc"
