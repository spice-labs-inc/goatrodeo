def gen_crls() -> list[str]:
    """Generate empty CRL, small CRL with revocations, SHA-1 CRL."""
    rows: list[str] = []
    dir_ = CORPUS_ROOT / "crls" / "synthetic"
    dir_.mkdir(parents=True, exist_ok=True)

    from cryptography.x509 import ocsp  # noqa: F401  # confirm lib is present
    from cryptography.hazmat.primitives.asymmetric import padding  # noqa: F401

    now = datetime(2026, 1, 1, tzinfo=timezone.utc)

    def _build_crl(hash_alg, revoked: list[int]) -> tuple[bytes, bytes]:
        """Build a CRL signed by a fresh RSA-2048 CA. Returns (PEM, DER)."""
        ca_key = rsa.generate_private_key(public_exponent=65537, key_size=2048)
        ca = _make_x509_selfsigned(
            ca_key, "GoatRodeo Test CA (CRL signer)",
            now, now + timedelta(days=3650),
            sig_hash=hash_alg,
        )
        crl_builder = (
            x509.CertificateRevocationListBuilder()
            .issuer_name(ca.subject)
            .last_update(now)
            .next_update(now + timedelta(days=30))
        )
        for serial in revoked:
            rev = (
                x509.RevokedCertificateBuilder()
                .serial_number(serial)
                .revocation_date(now)
                .build()
            )
            crl_builder = crl_builder.add_revoked_certificate(rev)
        crl = crl_builder.sign(private_key=ca_key, algorithm=hash_alg)
        return (crl.public_bytes(serialization.Encoding.PEM),
                crl.public_bytes(serialization.Encoding.DER))

    # 1. Empty PEM CRL (sha256)
    pem, _ = _build_crl(hashes.SHA256(), [])
    _write(dir_ / "empty-crl.pem", pem)
    _hand_sidecar(
        dir_, "empty-crl.pem",
        description="Empty X.509 CRL (no revocations)",
        source=SOURCE_GENERATED,
        mime_types=["application/x-pem-file", "application/pkix-crl"],
        purls=["<computed: pkg:x509/crl-sha256@... in Phase 4>"],
        metadata={"Certificates:RevokedCount": "0"},
    )
    rows.append(f"| synthetic/empty-crl.pem | {SOURCE_GENERATED} | {TODAY} | sha256:{_sha256(pem)} |")

    # 2. Small CRL with 3 revocations (PEM)
    pem, _ = _build_crl(hashes.SHA256(), [0x1001, 0x1002, 0x1003])
    _write(dir_ / "small-crl.pem", pem)
    _hand_sidecar(
        dir_, "small-crl.pem",
        description="Small X.509 CRL with 3 revocations (SHA-256 signed)",
        source=SOURCE_GENERATED,
        mime_types=["application/x-pem-file", "application/pkix-crl"],
        purls=["<computed in Phase 4>"],
        metadata={"Certificates:RevokedCount": "3"},
    )
    rows.append(f"| synthetic/small-crl.pem | {SOURCE_GENERATED} | {TODAY} | sha256:{_sha256(pem)} |")

    # 3. SHA-1 signed CRL (deprecated).
    # Again, cryptography refuses SHA-1 signing; we shell out to openssl
    # ca -gencrl, which requires a minimal CA config.
    with tempfile.TemporaryDirectory() as td:
        ca_key = os.path.join(td, "ca.key")
        ca_pem = os.path.join(td, "ca.pem")
        _sh(["openssl", "genpkey", "-algorithm", "RSA",
             "-pkeyopt", "rsa_keygen_bits:2048", "-out", ca_key])
        _sh(["openssl", "req", "-new", "-x509", "-key", ca_key,
             "-subj", "/CN=GoatRodeo Test SHA1 CRL CA",
             "-days", "3650", "-sha1", "-out", ca_pem])
        # minimal openssl.cnf for gencrl
        cfg = os.path.join(td, "openssl.cnf")
        Path(cfg).write_text(f"""
[ca]
default_ca = CA_default
[CA_default]
dir = {td}
database = {td}/index.txt
new_certs_dir = {td}
serial = {td}/serial
crlnumber = {td}/crlnumber
default_md = sha1
default_crl_days = 30
policy = policy_any
certificate = {ca_pem}
private_key = {ca_key}
[policy_any]
commonName = supplied
""")
        Path(f"{td}/index.txt").write_text("")
        Path(f"{td}/serial").write_text("1000\n")
        Path(f"{td}/crlnumber").write_text("1000\n")
        crl_pem_path = os.path.join(td, "sha1-crl.pem")
        _sh(["openssl", "ca", "-gencrl", "-config", cfg, "-out", crl_pem_path,
             "-md", "sha1"])
        sha1_crl_bytes = Path(crl_pem_path).read_bytes()
    _write(dir_ / "sha1-crl.pem", sha1_crl_bytes)
    _hand_sidecar(
        dir_, "sha1-crl.pem",
        description="CRL signed with SHA-1 (deprecated algorithm)",
        source=SOURCE_GENERATED,
        mime_types=["application/x-pem-file", "application/pkix-crl"],
        purls=["<computed in Phase 4>"],
        metadata={"Certificates:SigAlgorithm": "sha1-rsa"},
    )
    rows.append(f"| synthetic/sha1-crl.pem | {SOURCE_GENERATED} | {TODAY} | sha256:{_sha256(sha1_crl_bytes)} |")

    # 4. DER-encoded CRL (re-encoding of the small CRL)
    pem, der = _build_crl(hashes.SHA256(), [0x3001, 0x3002])
    _write(dir_ / "small-crl.der", der)
    _hand_sidecar(
        dir_, "small-crl.der",
        description="DER-encoded X.509 CRL (2 revocations)",
        source=SOURCE_GENERATED,
        mime_types=["application/pkix-crl"],
        purls=["<computed in Phase 4>"],
        metadata={"Certificates:RevokedCount": "2"},
    )
    rows.append(f"| synthetic/small-crl.der | {SOURCE_GENERATED} | {TODAY} | sha256:{_sha256(der)} |")
    return rows


