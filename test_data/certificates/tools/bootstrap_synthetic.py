from cryptography.x509.oid import NameOID

CORPUS_ROOT = Path(__file__).resolve().parents[1]
TODAY = date.today().isoformat()
TEST_BANNER = (
    "# GOAT RODEO TEST KEY - NOT A SECRET - DO NOT USE ANYWHERE ELSE\n"
)
SOURCE_GENERATED = "generated by test_data/certificates/tools/bootstrap_synthetic.py"


def _sh(cmd: list[str], *, cwd: str | None = None, input_bytes: bytes | None = None) -> bytes:
    """Run a command, capture stdout, raise on nonzero."""
    r = subprocess.run(
        cmd, cwd=cwd, input=input_bytes, check=True,
        stdout=subprocess.PIPE, stderr=subprocess.PIPE,
    )
    return r.stdout


def _write(path: Path, data: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)


def _write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def _append(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a", encoding="utf-8") as f:
        f.write(text)


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


# --- shared helpers ---

def _make_x509_selfsigned(
    key, subject_cn: str, not_before: datetime, not_after: datetime,
    is_ca: bool = True,
    sig_hash: hashes.HashAlgorithm | None = hashes.SHA256(),
) -> x509.Certificate:
    """Return a self-signed certificate with the given key + metadata."""
    name = x509.Name([
        x509.NameAttribute(NameOID.COMMON_NAME, subject_cn),
        x509.NameAttribute(NameOID.ORGANIZATION_NAME, "Goat Rodeo Test"),
        x509.NameAttribute(NameOID.COUNTRY_NAME, "US"),
    ])
    builder = (
        x509.CertificateBuilder()
        .subject_name(name)
        .issuer_name(name)
        .public_key(key.public_key())
        .serial_number(x509.random_serial_number())
        .not_valid_before(not_before)
        .not_valid_after(not_after)
    )
    if is_ca:
        builder = builder.add_extension(
            x509.BasicConstraints(ca=True, path_length=None), critical=True
        ).add_extension(
            x509.KeyUsage(
                digital_signature=True,
                content_commitment=False,
                key_encipherment=False,
                data_encipherment=False,
                key_agreement=False,
                key_cert_sign=True,
                crl_sign=True,
                encipher_only=False,
                decipher_only=False,
            ),
            critical=True,
        )
    # Ed25519 / Ed448 don't accept a hash algorithm argument
    from cryptography.hazmat.primitives.asymmetric import ed25519 as _ed25519
    from cryptography.hazmat.primitives.asymmetric import ed448 as _ed448
    if isinstance(key, (_ed25519.Ed25519PrivateKey, _ed448.Ed448PrivateKey)):
        return builder.sign(key, None)
    return builder.sign(key, sig_hash)


def _make_x509_intermediate(
    subject_cn: str,
    issuer_key, issuer_cert: x509.Certificate,
    not_before: datetime, not_after: datetime,
    sig_hash: hashes.HashAlgorithm = hashes.SHA256(),
):
    """Return an intermediate cert signed by `issuer_key`."""
    key = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    name = x509.Name([
        x509.NameAttribute(NameOID.COMMON_NAME, subject_cn),
        x509.NameAttribute(NameOID.ORGANIZATION_NAME, "Goat Rodeo Test"),
        x509.NameAttribute(NameOID.COUNTRY_NAME, "US"),
    ])
    cert = (
        x509.CertificateBuilder()
        .subject_name(name)
        .issuer_name(issuer_cert.subject)
        .public_key(key.public_key())
        .serial_number(x509.random_serial_number())
        .not_valid_before(not_before)
        .not_valid_after(not_after)
        .add_extension(x509.BasicConstraints(ca=True, path_length=0), critical=True)
        .sign(issuer_key, sig_hash)
    )
    return key, cert


def _write_cert_fixture(
    dir_: Path, stem: str, cert: x509.Certificate,
    *, description: str, source: str, der: bool = False
) -> None:
    if der:
        data = cert.public_bytes(serialization.Encoding.DER)
        ext = "der"
        mime_types = ["application/pkix-cert"]
    else:
        data = cert.public_bytes(serialization.Encoding.PEM)
        ext = "pem"
        mime_types = ["application/x-pem-file", "application/x-x509-ca-cert"]
    fixture_path = dir_ / f"{stem}.{ext}"
    _write(fixture_path, data)
    # Compute sidecar from DER bytes
    der_bytes = cert.public_bytes(serialization.Encoding.DER)
    sc = cert_sidecar.x509_sidecar(
        der_bytes, description=description, source=source,
        retrieved_at=TODAY, mime_types=mime_types,
    )
    cert_sidecar.write_sidecar(str(dir_ / f"{stem}.{ext}.expected.json"), sc)


