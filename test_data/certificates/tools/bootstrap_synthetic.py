#!/usr/bin/env python3
"""Generate synthetic fixtures + sidecars across all Certificates categories.

Covers:

  - `x509/synthetic/` — Ed25519 self-signed, ECDSA P-256, ECDSA P-384,
    RSA-2048, SHA-1-signed RSA, non-self-signed (intermediate signed by
    CA), DER re-encoding of one fixture
  - `crls/synthetic/` — empty CRL, small CRL with revocations, SHA-1
    signed CRL
  - `ssh/synthetic/` — rsa-4096, ed25519, ecdsa-nistp256, ecdsa-nistp384
    public keys; OpenSSH CA-signed user cert and host cert (cross-
    algorithm)
  - `pgp/synthetic/` — v4 RSA and v4 Ed25519 armored public keys
  - `private-keys/synthetic/` — unencrypted PKCS#8 RSA / Ed25519;
    OpenSSH unencrypted RSA-4096 / Ed25519; encrypted PKCS#8 AES-256
    PBKDF2; encrypted PKCS#8 scrypt; OpenSSH-encrypted Ed25519;
    legacy PEM encrypted RSA
  - `keystores/synthetic/` — JKS, JCEKS, PKCS#12 (unencrypted +
    encrypted)
  - `pem-bundles/synthetic/` — small 2-cert chain
  - `edge-cases/` — truncated, corrupt, empty, whitespace-only,
    blank-lines, typo-header, wrong-magic variants, plain-text

Each fixture is paired with a sidecar computed from the generated
bytes where ground truth can be derived (X.509), or a hand-written
sidecar for non-X.509 fixtures whose ground truth the Certificates
strategy will produce in Phase 4-7.

## Discipline

- The script is idempotent — re-running overwrites existing fixtures.
- Private-key fixtures that land in the repo carry the banner
  `# GOAT RODEO TEST KEY - NOT A SECRET - DO NOT USE ANYWHERE ELSE`
  per the policy in `test_data/certificates/private-keys/SOURCES.md`.
- Transient private keys used only to synthesize other artifacts
  (e.g., the test CA that signs intermediate certs) are generated
  in a tmp dir and deleted before exit.

## Invariant compliance

- Invariant #13: the script needs openssl, ssh-keygen, gpg, keytool,
  and Python's `cryptography` library. The Docker image at
  `test_data/certificates/tools/Dockerfile` ships all of these.
"""

