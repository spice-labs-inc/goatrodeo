#!/usr/bin/env python3
"""Refresh src/main/resources/spring_maven_groups.tsv from Maven Central.

Spring's own jars ship without pom.properties, and their manifests don't name
the Maven groupId, so `KnownMavenGroups` looks the groupId up in this snapshot
of Maven Central. Rerun this script from time to time to pick up new Spring
artifacts:

    python3 -I scripts/refresh_spring_artifacts.py

Only jar-packaged artifacts whose artifactId starts with `spring-` are kept.
When an artifactId exists under more than one group (a relocation, such as
spring-modulith moving out of org.springframework.experimental), the group
with the most recent release wins.
"""

import json
import pathlib
import sys
import time
import urllib.parse
import urllib.request

SEARCH = "https://search.maven.org/solrsearch/select"
PAGE = 200
OUT = (
    pathlib.Path(__file__).resolve().parent.parent
    / "src/main/resources/spring_maven_groups.tsv"
)


def fetch(start):
    query = urllib.parse.urlencode(
        {"q": "g:org.springframework*", "rows": PAGE, "start": start, "wt": "json"}
    )
    for attempt in range(5):
        try:
            with urllib.request.urlopen(f"{SEARCH}?{query}", timeout=60) as resp:
                return json.load(resp)["response"]
        except Exception as e:  # transient Maven Central errors are common
            if attempt == 4:
                raise
            print(f"retrying page at {start}: {e}", file=sys.stderr)
            time.sleep(2 ** attempt)


def main():
    latest = {}
    start = 0
    while True:
        response = fetch(start)
        docs = response["docs"]
        for doc in docs:
            if doc.get("p") in ("jar", "bundle") and doc["a"].startswith("spring-"):
                best = latest.get(doc["a"])
                if best is None or doc["timestamp"] > best[1]:
                    latest[doc["a"]] = (doc["g"], doc["timestamp"])
        start += len(docs)
        if not docs or start >= response["numFound"]:
            break
    lines = [f"{a}\t{g}" for a, (g, _) in sorted(latest.items())]
    OUT.write_text(
        "# artifactId<TAB>groupId of Spring jars on Maven Central.\n"
        "# Generated by scripts/refresh_spring_artifacts.py; do not edit by hand.\n"
        + "\n".join(lines)
        + "\n"
    )
    print(f"wrote {len(lines)} artifacts to {OUT}")


if __name__ == "__main__":
    main()
