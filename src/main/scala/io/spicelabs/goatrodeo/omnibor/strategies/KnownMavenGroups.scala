package io.spicelabs.goatrodeo.omnibor.strategies

import scala.io.Source
import scala.util.Using

/** Maven groupIds for Spring jars, which ship without `pom.properties` and
  * whose manifests don't name the groupId.
  *
  * Nothing inside the jar can tell `spring-boot` (group
  * `org.springframework.boot`) apart from `spring-beans` (group
  * `org.springframework`), so the groupId comes from a snapshot of Maven
  * Central in `spring_maven_groups.tsv`, generated by
  * `scripts/refresh_spring_artifacts.py`. Artifacts released after the snapshot
  * fall back to `projectPrefixes`, keyed by artifactId prefix.
  */
private[strategies] object KnownMavenGroups {

  /** artifactId → groupId for every Spring jar in the Maven Central snapshot.
    */
  private[strategies] lazy val springSnapshot: Map[String, String] =
    Using.resource(
      Source.fromInputStream(
        getClass.getResourceAsStream("/spring_maven_groups.tsv"),
        "UTF-8"
      )
    ) { source =>
      source
        .getLines()
        .filterNot(line => line.isEmpty || line.startsWith("#"))
        .map { line =>
          val Array(artifactId, groupId) = line.split('\t')
          artifactId -> groupId
        }
        .toMap
    }

  /** Fallback for Spring artifacts newer than the snapshot: the longest
    * matching `-`-delimited artifactId prefix wins, and plain `spring` covers
    * Spring Framework itself.
    */
  private[strategies] val projectPrefixes: Map[String, String] = Map(
    "spring" -> "org.springframework",
    "spring-ai" -> "org.springframework.ai",
    "spring-amqp" -> "org.springframework.amqp",
    "spring-rabbit" -> "org.springframework.amqp",
    "spring-batch" -> "org.springframework.batch",
    "spring-boot" -> "org.springframework.boot",
    "spring-cloud" -> "org.springframework.cloud",
    "spring-credhub" -> "org.springframework.credhub",
    "spring-data" -> "org.springframework.data",
    "spring-graphql" -> "org.springframework.graphql",
    "spring-grpc" -> "org.springframework.grpc",
    "spring-hateoas" -> "org.springframework.hateoas",
    "spring-integration" -> "org.springframework.integration",
    "spring-kafka" -> "org.springframework.kafka",
    "spring-ldap" -> "org.springframework.ldap",
    "spring-modulith" -> "org.springframework.modulith",
    "spring-pulsar" -> "org.springframework.pulsar",
    "spring-restdocs" -> "org.springframework.restdocs",
    "spring-retry" -> "org.springframework.retry",
    "spring-security" -> "org.springframework.security",
    "spring-session" -> "org.springframework.session",
    "spring-shell" -> "org.springframework.shell",
    "spring-statemachine" -> "org.springframework.statemachine",
    "spring-vault" -> "org.springframework.vault",
    "spring-webflow" -> "org.springframework.webflow",
    "spring-ws" -> "org.springframework.ws"
  )

  /** The groupId of a Spring artifact, or None if `artifactId` isn't Spring's.
    */
  def springGroupId(artifactId: String): Option[String] =
    springSnapshot.get(artifactId).orElse {
      val tokens = artifactId.split('-')
      (tokens.length to 1 by -1).iterator
        .map(n => tokens.take(n).mkString("-"))
        .collectFirst(Function.unlift(projectPrefixes.get))
    }
}
