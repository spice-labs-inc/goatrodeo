  /** Get the companion POM file for a JAR, if it exists.
    *
    * For `foo-1.0.jar`, the companion POM is `foo-1.0.pom`. For
    * `foo-1.0-sources.jar`, the companion POM is `foo-1.0.pom`.
    */
  private def companionPom(jarFile: File): Option[File] = {
    val basePath = jarFile.getAbsolutePath
    val strippedPath = basePath
      .stripSuffix("-sources.jar")
      .stripSuffix("-javadoc.jar")
      .stripSuffix("-javadocs.jar")
      .stripSuffix(".jar")
      .stripSuffix(".war")
      .stripSuffix(".ear")
      .stripSuffix(".hpi")
    val pomPath = strippedPath + ".pom"
    val pomFile = new File(pomPath)
    if (pomFile.exists()) Some(pomFile) else None
  }

  /** Parse a companion POM file to extract groupId/artifactId/version.
    *
    * Uses the production PomParser (same code Goat Rodeo uses), so the test
    * verifies the actual parsing behavior, not a test-only reimpl.
    */
  private def parseCompanionPom(pomFile: File): Option[ParsedPom] = {
    val content = Source.fromFile(pomFile).mkString
    PomParser.parse(content)
  }

  /** Process a JAR (with companion POM) through the full Maven pipeline.
    *
    * Copies the JAR and companion POM to a temp directory, then calls
    * processDirectoryWithStore to run the full pipeline.
    */
  private def processCorpusJar(jarFile: File): MemStorage = {
    MavenTestHelpers.withTempDir(s"phase6-${jarFile.getName}") { dir =>
      val destJar = new File(dir, jarFile.getName)
      Files.copy(jarFile.toPath, destJar.toPath)

      companionPom(jarFile).foreach { pom =>
        val destPom = new File(dir, pom.getName)
        Files.copy(pom.toPath, destPom.toPath)
      }

      MavenTestHelpers.processDirectoryWithStore(dir)
    }
  }

  /** Extract the canonical pURL from a JAR's metadata. */
  private def extractCanonicalPurl(
      store: MemStorage,
      jarFile: File
  ): Option[String] = {
    val artifact = FileWrapper(jarFile, jarFile.getName, None)
    val (gitoid, _) = GitOIDUtils.computeAllHashes(artifact)

    store.read(gitoid).flatMap { item =>
      item.bodyAsItemMetaData.flatMap { meta =>
        meta.extra
          .get(MetadataKeyConstants.CANONICAL_PURL)
          .flatMap(_.headOption.map(_.value))
      }
    }
  }

  /** Extract all pURLs (alias:from) for a JAR from the store. */
  private def extractGoatRodeoPurls(
      store: MemStorage,
      jarFile: File
  ): Set[String] = {
    val artifact = FileWrapper(jarFile, jarFile.getName, None)
    val (gitoid, _) = GitOIDUtils.computeAllHashes(artifact)

    store.read(gitoid) match {
      case Some(item) =>
        item.connections
          .filter(_._1 == EdgeType.aliasFrom)
          .map(_._2)
          .filter(_.startsWith("pkg:"))
          .toSet
      case None => Set.empty
    }
  }

  /** Extract the artifactId from a filename. `Agrona-0.1.jar` -> `Agrona`
    * `abris-0.0.1.jar` -> `abris`
    */
  private def filenameArtifactId(name: String): String = {
    val withoutExt = name.replaceAll("\\.(jar|war|ear|hpi)$", "")
    val lastDash = withoutExt.lastIndexOf('-')
    if (lastDash > 0) withoutExt.substring(0, lastDash)
    else withoutExt
  }

  // =========================================================================
  // Test 6.3: "Better than the reference scanner" — canonical pURL uses POM groupId
  // =========================================================================
  //
  // What it tests:
  //   For corpus JARs with companion POMs, Goat Rodeo's canonical pURL
  //   uses the companion POM's groupId — NOT the filename. This
  //   demonstrates Goat Rodeo is "better than the reference scanner" because the reference scanner often
  //   uses the filename/pathname as the groupId (a known reference scanner failure).
  //
  // Why it's relevant:
  //   REQ-6 — "Goat Rodeo pURLs must either match what the reference scanner finds or be
  //   better than what the reference scanner finds. The reference scanner will often use the filename/pathname
  //   as the groupId and artifactId — this is a failure on the reference scanner's part."
  //
  // Requirement section:
  //   REQ-6.
  //
  // Theory:
  //   For each corpus JAR with a companion POM:
  //   1. Parse the companion POM to get expected groupId.
  //   2. Process the JAR through the full pipeline.
  //   3. Extract the canonical pURL.
  //   4. Assert the canonical pURL's groupId matches the POM's groupId.
  //   5. Assert the canonical pURL's groupId is NOT the filename (which
  //      is what the reference scanner would use if it fell back to filename-derived pURL).

