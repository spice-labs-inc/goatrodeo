/* Phase 6: Metadata Parity — Regular JARs and BestPurlSuite
 *
 * '''What this suite tests:'''
 *   - REQ-6: Goat Rodeo pURLs must either match what the reference scanner finds or be
 *     better than what the reference scanner finds for regular JARs.
 *   - GAP-5: MultiplePurlSuite (already passing — 113 tests, covered
 *     in Phase 2 rewrite).
 *   - GAP-8: BestPurlSuite (already passing — 2 tests).
 *   - Test 6.3: "Better than the reference scanner" — Goat Rodeo uses companion POM for
 *     canonical pURL, not the filename.
 *   - Test 6.4: Maven Central validation — canonical pURLs match
 *     coordinates verified to exist in Maven Central.
 *   - Test 6.6: Companion POM priority in full pipeline — canonical
 *     pURL comes from POM, not manifest or pom.properties.
 *
 * '''What this suite does NOT test:'''
 *   - Test 6.1 (MultiplePurlSuite) — already covered by MultiplePurlSuite
 *     (113 tests, rewritten in Phase 2).
 *   - Test 6.2 (BestPurlSuite) — already covered by BestPurlSuite
 *     (2 tests, passing).
 *   - Test 6.5 (pURL count >= reference scanner count) — implicitly covered by
 *     MultiplePurlSuite superset check (superset implies count >=).
 *   - Test 6.7 (property-based superset) — same as MultiplePurlSuite.
 *
 * '''Maven Central verification:'''
 * Each coordinate in Test 6.4 was manually verified to exist in Maven
 * Central at https://repo1.maven.org/maven2/ on 2026-07-08. No runtime
 * Maven Central queries are performed.
 *
 * '''LLM context:''' This suite verifies that Goat Rodeo produces pURLs
 * that (a) match real Maven Central artifacts and (b) are derived from
 * the companion POM rather than the filename — making them more accurate
 * than the reference scanner's filename-derived pURLs.
 */
class Phase6MetadataParityRegularBestPurlSuite extends FunSuite {

