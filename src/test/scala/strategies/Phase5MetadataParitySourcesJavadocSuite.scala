  // Requirement section:
  //   GAP-7 + REQ-5.

  // Reuse sampled sources JARs (first 5 with pom.properties)
  private val sampledForMetadata: Vector[File] = {
    sampledSourcesJars
      .filter(j => extractPomProperties(j).nonEmpty)
      .take(5)
  }

  sampledForMetadata.foreach { jarFile =>
    test(s"Test 5.6: ${jarFile.getName} — canonical pURL in metadata") {
      val store = processCorpusJar(jarFile)
      val canonicalPurlOpt = extractCanonicalPurl(store, jarFile)

      assert(
