      )
    }
  }

  // =========================================================================
  // Test 5.7: Standalone sources JAR (no companion POM) still emits pURLs
  // =========================================================================
  //
  // What it tests:
  //   Sources JARs without a companion POM (no main JAR in the same
  //   directory) still emit pURLs with `?packaging=sources`.
  //
  // Why it's relevant:
  //   `computeMavenFiles` has a second pass that claims standalone
  //   sources/javadoc JARs. These get `MavenToProcess(a, None, None, None, None)`
  //   — no companion POM. The canonical pURL falls back to JAR contents
  //   then filename.
  //
  // Requirement section:
  //   REQ-5.

  private val standaloneSourcesJars: Vector[File] = {
    sourcesJars.filter { jar =>
      companionMainJar(jar).isEmpty && companionPom(jar).isEmpty
    }
  }

  // Sample 5 standalone sources JARs
  private val sampledStandalone: Vector[File] = {
    if (standaloneSourcesJars.isEmpty) Vector.empty
    else {
      val step = math.max(1, standaloneSourcesJars.length / 5)
      standaloneSourcesJars.indices
        .filter(_ % step == 0)
        .map(standaloneSourcesJars(_))
        .toVector
    }
  }

  sampledStandalone.foreach { jarFile =>
    test(s"Test 5.7: ${jarFile.getName} — standalone sources JAR emits pURLs") {
      val store = processCorpusJar(jarFile)
      val goatPurls = extractGoatRodeoPurls(store, jarFile)

      assert(
        goatPurls.nonEmpty,
        s"Standalone sources JAR should emit at least one pURL.\nJAR: ${jarFile.getAbsolutePath}"
      )

      // ALL pURLs must have ?packaging=sources (structured check)
      val withoutClassifier =
        goatPurls.filterNot(PurlParts.hasQualifier(_, "packaging", "sources"))
      assert(
        withoutClassifier.isEmpty,
        s"""Standalone sources JAR pURLs without ?packaging=sources:
           |  ${withoutClassifier.toList.sorted.mkString("\n  ")}
           |
           |All pURLs: ${goatPurls.toList.sorted.mkString("\n  ")}
           |JAR: ${jarFile.getAbsolutePath}
           |""".stripMargin
      )

      // Verify pURL coordinates are correct, not just non-empty.
      // For JARs with pom.properties: assert superset of expected pURLs.
      // For JARs without pom.properties: assert at least one pURL's
      // artifactId matches the filename-derived artifactId.
      val props = extractPomProperties(jarFile)
      if (props.nonEmpty) {
        val expected = buildExpectedPurls(props, "packaging=sources")
        val normalizedGoat = goatPurls.map(PurlParts.normalize)
        val normalizedExpected = expected.map(PurlParts.normalize)
        val missing = normalizedExpected -- normalizedGoat
        assert(
          missing.isEmpty,
          s"""Goat Rodeo is missing ${missing.size} of ${expected.size} expected pURLs (from pom.properties).
             |
             |Missing:
             |  ${missing.toList.sorted.mkString("\n  ")}
             |
             |Goat Rodeo pURLs:
             |  ${goatPurls.toList.sorted.mkString("\n  ")}
             |
             |JAR: ${jarFile.getAbsolutePath}
             |""".stripMargin
        )
      } else {
        // No pom.properties — verify at least one pURL's artifactId
        // matches the filename-derived artifactId. This ensures the
        // pURL is not garbage.
        val fnameArt = {
          val name = jarFile.getName
          val stripped = name
            .stripSuffix("-sources.jar")
            .stripSuffix("-javadoc.jar")
            .stripSuffix("-javadocs.jar")
          val lastDash = stripped.lastIndexOf('-')
          if (lastDash > 0) stripped.substring(0, lastDash)
          else stripped
        }
        val goatArtifactIds = goatPurls.flatMap(PurlParts.artifactIdOf)
        assert(
          goatArtifactIds.contains(fnameArt),
          s"""No pURL artifactId matches the filename-derived artifactId '$fnameArt'.
             |
             |Goat Rodeo artifactIds: ${goatArtifactIds.toList.sorted.mkString(
              ", "
            )}
             |Filename-derived artifactId: $fnameArt
             |
             |Goat Rodeo pURLs:
             |  ${goatPurls.toList.sorted.mkString("\n  ")}
             |
             |JAR: ${jarFile.getAbsolutePath}
             |""".stripMargin
        )
      }

      // Metadata ground truth parity
      assertMetadataParity(jarFile, goatPurls)
    }
  }

  // =========================================================================
  // Test 5.8: For any sources JAR in corpus, pURL count >= pom.properties count
  // =========================================================================
  //
  // What it tests:
  //   For any sources JAR, Goat Rodeo finds at least as many pURLs as
  //   there are embedded `pom.properties` entries.
  //
  // Requirement section:
  //   REQ-5.

  // Reuse sampled sources JARs
  sampledSourcesJars.foreach { jarFile =>
    val props = extractPomProperties(jarFile)
    if (props.nonEmpty) {
      test(
        s"Test 5.8: ${jarFile.getName} — pURL count >= pom.properties count (${props.size})"
      ) {
        val store = processCorpusJar(jarFile)
        val goatPurls = extractGoatRodeoPurls(store, jarFile)

        assert(
          goatPurls.size >= props.size,
          s"""Goat Rodeo found ${goatPurls.size} pURLs but expected >= ${props.size} (pom.properties count).
             |
             |Goat Rodeo pURLs:
             |  ${goatPurls.toList.sorted.mkString("\n  ")}
             |
             |Expected pom.properties tuples:
             |  ${props
              .map(p => s"${p.groupId}/${p.artifactId}@${p.version}")
              .mkString("\n  ")}
             |
             |JAR: ${jarFile.getAbsolutePath}
             |""".stripMargin
        )

        // Metadata ground truth parity
        assertMetadataParity(jarFile, goatPurls)
      }
    }
  }
