  // =========================================================================
  // Test 5.5: Sources JAR with companion POM uses POM for canonical pURL
  // =========================================================================
  //
  // What it tests:
  //   For sources JARs in the corpus that have a companion `.pom` file,
  //   the canonical pURL uses the companion POM's groupId/artifactId/version
  //   (not the filename or manifest).
  //
  // Why it's relevant:
  //   Verifies Phase 2 (canonical priority) works against real corpus
  //   data for sources JARs.
  //
  // Requirement section:
  //   REQ-3 + REQ-5.

  private val sourcesJarsWithPom: Vector[File] = {
    sampledSourcesJars.filter(companionPom(_).isDefined)
  }

  // Sample 10 sources JARs with companion POMs for this test
  private val sampledWithPom: Vector[File] = {
    if (sourcesJarsWithPom.isEmpty) Vector.empty
    else {
      val step = math.max(1, sourcesJarsWithPom.length / 10)
      sourcesJarsWithPom.indices
        .filter(_ % step == 0)
        .map(sourcesJarsWithPom(_))
        .toVector
    }
  }

  sampledWithPom.foreach { jarFile =>
    test(s"Test 5.5: ${jarFile.getName} — canonical pURL from companion POM") {
      // Parse the companion POM to get expected coordinates
      val pomOpt = companionPom(jarFile)
      assert(pomOpt.isDefined, s"Companion POM should exist for: $jarFile")
      val parsedPom = parseCompanionPom(pomOpt.get)
      assert(
        parsedPom.isDefined,
        s"Failed to parse companion POM: ${pomOpt.get}"
      )

      val pomG = parsedPom.get.groupId.orElse(parsedPom.get.parentGroupId)
      val pomA = parsedPom.get.artifactId
      val pomV = parsedPom.get.version.orElse(parsedPom.get.parentVersion)

      assert(pomG.isDefined, s"POM groupId not found: ${pomOpt.get}")
      assert(pomA.isDefined, s"POM artifactId not found: ${pomOpt.get}")
      assert(pomV.isDefined, s"POM version not found: ${pomOpt.get}")

      val store = processCorpusJar(jarFile)
      val canonicalPurlOpt = extractCanonicalPurl(store, jarFile)

      assert(
        canonicalPurlOpt.isDefined,
        s"Canonical pURL should be present for sources JAR with companion POM.\nJAR: ${jarFile.getAbsolutePath}"
      )

      val canonicalPurl = canonicalPurlOpt.get

      // Structured check: canonical pURL must have ?packaging=sources qualifier
      assert(
        PurlParts.hasQualifier(canonicalPurl, "packaging", "sources"),
        s"Canonical pURL should have ?packaging=sources.\nCanonical: $canonicalPurl\nJAR: ${jarFile.getAbsolutePath}"
      )

      // Structured comparison: canonical pURL's GAV must match the POM's GAV.
      // This is the core assertion that was missing — previously the test
      // only checked that a canonical pURL existed with the right qualifier,
      // but never verified the coordinates came from the POM.
      val purlParts = PurlParts.parse(canonicalPurl)
      assert(
        purlParts.isDefined,
        s"Failed to parse canonical pURL: $canonicalPurl"
      )

      purlParts.foreach { parts =>
        assert(
          parts.groupId == pomG.get,
          s"""Canonical pURL groupId should come from companion POM, not filename or manifest.
             |
             |Expected (from POM): ${pomG.get}
             |Actual (from pURL):  ${parts.groupId}
             |Canonical pURL: $canonicalPurl
             |POM file: ${pomOpt.get.getAbsolutePath}
             |JAR: ${jarFile.getAbsolutePath}
             |""".stripMargin
        )
        assert(
          parts.artifactId == pomA.get,
          s"""Canonical pURL artifactId should come from companion POM.
             |
             |Expected (from POM): ${pomA.get}
             |Actual (from pURL):  ${parts.artifactId}
             |Canonical pURL: $canonicalPurl
             |JAR: ${jarFile.getAbsolutePath}
             |""".stripMargin
        )
        assert(
          parts.version == pomV.get,
          s"""Canonical pURL version should come from companion POM.
             |
             |Expected (from POM): ${pomV.get}
             |Actual (from pURL):  ${parts.version}
             |Canonical pURL: $canonicalPurl
             |JAR: ${jarFile.getAbsolutePath}
             |""".stripMargin
        )
      }

      // Also verify against metadata ground truth
      val goatPurls = extractGoatRodeoPurls(store, jarFile)
      assertMetadataParity(jarFile, goatPurls)
    }
  }

  // =========================================================================
  // Test 5.6: Sources JAR canonical pURL in metadata
  // =========================================================================
  //
  // What it tests:
  //   For sources JARs in the corpus, the gitoid Item's metadata contains
  //   `CanonicalPurl` key with correct value (including `?packaging=sources`).
