/* Phase 5: Metadata Parity — Sources and Javadoc JARs
 *
 * '''What this suite tests:'''
 *   - REQ-5: For sources and javadoc JARs in the test corpus, Goat Rodeo
 *     pURLs must either match what the reference scanner finds or
 *     be better than what the reference scanner finds.
 *   - GAP-6: Metadata parity tests for sources/javadoc JARs
 *   - HS-4: Tests use the ACTUAL test corpus — real JAR files from
 *     `/data/test_data/`. Expected pURLs are extracted at test time by
 *     unzipping each JAR and reading its `META-INF/maven/.../pom.properties`
 *     entries.
 *
 * '''What this suite does NOT test:'''
 *   - Synthetic JARs (those are in Phase4SecondaryClassifierSuite)
 *   - Regular JAR metadata parity (that's MultiplePurlSuite, Phase 6)
 *   - Maven Central validation (that's BestPurlSuite, Phase 6)
 *
 * '''LLM context:''' This suite verifies that Goat Rodeo finds all pURLs
 * from embedded pom.properties in sources and javadoc JARs in the real
 * test corpus, and that its pURL count and artifactId set are at least
 * as comprehensive as the reference scanner output. It does NOT use
 * pre-computed data — it opens each JAR at test time, reads
 * pom.properties, builds expected pURLs, and compares against what
 * Goat Rodeo actually emits. It also loads static metadata ground truth.
 *
 * '''Test corpus stats:'''
 *   - 3051 sources JARs (files ending in `-sources.jar`)
 *   - 1 javadoc JAR (`wps-demo-1.3.0-javadoc.jar`)
 *   - 2995 sources JARs with companion POM
 *   - 56 standalone sources JARs (no main JAR, no POM)
 *
 * '''Sampling:''' Tests 5.3-5.8 sample from the corpus to keep test
 * runtime reasonable (~5 minutes). The sampling is deterministic (sorted
 * by path, every Nth file) to ensure reproducibility.
 */
class Phase5MetadataParitySourcesJavadocSuite extends FunSuite {

  // =========================================================================
  // Metadata ground truth (generated by reference scanner, loaded at test time)
  // =========================================================================

  private val metadataEntries =
    MetadataGroundTruth.loadEntries("metadata_sources_javadocs.json")

  // =========================================================================
  // Test corpus discovery
  // =========================================================================

  private val testDataDir = new File("test_data")

  /** All sources JARs in the corpus, sorted by path for determinism. */
  private lazy val sourcesJars: Vector[File] = {
    findFiles(testDataDir, _.toLowerCase.endsWith("-sources.jar"))
  }

  /** All javadoc JARs in the corpus, sorted by path for determinism. */
  private lazy val javadocJars: Vector[File] = {
    findFiles(
      testDataDir,
      f =>
        f.toLowerCase.endsWith("-javadoc.jar") ||
          f.toLowerCase.endsWith("-javadocs.jar")
    )
  }

  /** Recursively find files matching a predicate. */
  private def findFiles(dir: File, pred: String => Boolean): Vector[File] = {
    if (!dir.exists()) return Vector.empty
    val result = scala.collection.mutable.ArrayBuffer[File]()
    def scan(d: File): Unit = {
      val entries = d.listFiles()
      if (entries != null) {
        for (e <- entries) {
          if (e.isFile && pred(e.getName)) {
            result += e
          } else if (e.isDirectory) {
            scan(e)
          }
        }
      }
    }
    scan(dir)
    result.toVector.sorted
  }

  /** Get the companion POM file for a JAR, if it exists.
    *
    * For `foo-1.0-sources.jar`, the companion POM is `foo-1.0.pom` (the POM is
    * shared between the main JAR and the sources JAR — Maven does not publish
    * separate POMs for sources/javadoc JARs). For `foo-1.0.jar`, the companion
    * POM is `foo-1.0.pom`.
    */
  private def companionPom(jarFile: File): Option[File] = {
    val basePath = jarFile.getAbsolutePath
    // Strip -sources.jar, -javadoc.jar, -javadocs.jar, .jar, .war, etc.
    val strippedPath = basePath
      .stripSuffix("-sources.jar")
      .stripSuffix("-javadoc.jar")
      .stripSuffix("-javadocs.jar")
      .stripSuffix(".jar")
      .stripSuffix(".war")
      .stripSuffix(".ear")
      .stripSuffix(".hpi")
    val pomPath = strippedPath + ".pom"
    val pomFile = new File(pomPath)
    if (pomFile.exists()) Some(pomFile) else None
  }

  /** Get the companion main JAR for a sources JAR, if it exists.
    *
    * For `foo-1.0-sources.jar`, the main JAR is `foo-1.0.jar`.
    */
  private def companionMainJar(jarFile: File): Option[File] = {
    val basePath = jarFile.getAbsolutePath
    if (basePath.endsWith("-sources.jar")) {
      val mainJarPath = basePath.stripSuffix("-sources.jar") + ".jar"
      val mainJarFile = new File(mainJarPath)
      if (mainJarFile.exists()) Some(mainJarFile) else None
    } else None
  }

  // =========================================================================
  // Expected pURL extraction from JAR at test time (HS-4)
  // =========================================================================

  /** Case class for a parsed pom.properties tuple. */
  case class PomProps(groupId: String, artifactId: String, version: String)

  /** Extract all pom.properties tuples from a JAR at test time.
    *
    * Opens the JAR as a ZipFile, finds all `META-INF/maven/.../pom.properties`
    * entries, parses each to extract groupId/artifactId/version.
    *
    * This is the "expected" data source — NOT pre-computed, NOT cached, NOT
    * from a JSON file. Each JAR is opened and parsed fresh at test time per
    * HS-4.
    *
    * @param jarFile
    *   the JAR file to extract from
    * @return
    *   a vector of parsed pom.properties tuples (deduplicated)
    */
  private def extractPomProperties(jarFile: File): Vector[PomProps] = {
    val zip = new ZipFile(jarFile)
    try {
      val entries = zip
        .entries()
        .asScala
        .toVector
        .filter { e =>
          val lower = e.getName.toLowerCase
          lower.startsWith("meta-inf/maven/") &&
          lower.endsWith("/pom.properties")
        }

      val tuples = entries.flatMap { entry =>
        val content = scala.io.Source
          .fromInputStream(
            zip.getInputStream(entry)
          )
          .mkString
        parsePomProperties(content)
      }

      tuples.distinct
    } finally {
      zip.close()
    }
  }

  /** Parse a pom.properties file content to extract groupId/artifactId/version.
    *
    * Mimics the Maven pipeline's `parsePropertiesString` — lowercases keys,
    * strips comments, extracts key=value pairs.
    */
  private def parsePomProperties(content: String): Option[PomProps] = {
    val props = content.linesIterator
      .map(_.trim)
      .filterNot(_.startsWith("#"))
      .filter(_.contains("="))
      .map { line =>
        val idx = line.indexOf('=')
        line.substring(0, idx).trim.toLowerCase -> line.substring(idx + 1).trim
      }
      .toMap

    for {
      g <- props.get("groupid")
      a <- props.get("artifactid")
      v <- props.get("version")
      if g.nonEmpty && a.nonEmpty && v.nonEmpty
    } yield PomProps(g, a, v)
  }

  /** Build expected pURL set from pom.properties tuples.
    *
    * Each tuple produces a pURL string:
    * `pkg:maven/<groupId>/<artifactId>@<version>?packaging=sources` for sources
    * JARs, or `pkg:maven/<groupId>/<artifactId>@<version>?classifier=javadoc`
    * for javadoc JARs.
    *
    * Note: These are the EXPECTED pURLs — the minimum set Goat Rodeo must find.
    * Goat Rodeo may find additional pURLs (from manifest, embedded pom.xml,
    * etc.), which is acceptable (superset).
    */
  private def buildExpectedPurls(
      tuples: Vector[PomProps],
      classifier: String
  ): Set[String] = {
    tuples.map { t =>
      s"pkg:maven/${t.groupId}/${t.artifactId}@${t.version}?$classifier"
    }.toSet
  }

  // =========================================================================
  // Process a corpus JAR through the Goat Rodeo pipeline
  // =========================================================================

  /** Process a sources or javadoc JAR through the full Maven pipeline.
    *
    * Copies the JAR (and companion POM if it exists) to a temp directory, then
    * calls `processDirectoryWithStore` to run the full pipeline. This exercises
    * the companion POM bundling (REQ-8) and processing order (POM → Sources →
    * Javadoc → JAR) (REQ-4).
    *
    * Returns the store with all emitted pURLs and metadata.
    */
  private def processCorpusJar(
      jarFile: File
  ): MemStorage = {
    MavenTestHelpers.withTempDir(s"phase5-${jarFile.getName}") { dir =>
      val destJar = new File(dir, jarFile.getName)
      Files.copy(jarFile.toPath, destJar.toPath)

      // Copy companion POM if it exists
      companionPom(jarFile).foreach { pom =>
        val destPom = new File(dir, pom.getName)
        Files.copy(pom.toPath, destPom.toPath)
      }

      // Copy companion main JAR if it exists (so computeMavenFiles bundles
      // the sources JAR as a companion, not standalone)
      companionMainJar(jarFile).foreach { mainJar =>
        val destMain = new File(dir, mainJar.getName)
        Files.copy(mainJar.toPath, destMain.toPath)
      }

      val store = MavenTestHelpers.processDirectoryWithStore(dir)
      store
    }
  }

  /** Extract pURLs emitted by Goat Rodeo for a specific JAR.
    *
    * Computes the gitoid of the JAR, reads the corresponding Item from the
    * store, and extracts the `alias:from` connections (pURLs).
    */
  private def extractGoatRodeoPurls(
      store: MemStorage,
      jarFile: File
  ): Set[String] = {
    val artifact = FileWrapper(jarFile, jarFile.getName, None)
    val (gitoid, _) = GitOIDUtils.computeAllHashes(artifact)

    store.read(gitoid) match {
      case Some(item) =>
        item.connections
          .filter(_._1 == EdgeType.aliasFrom)
          .map(_._2)
          .filter(_.startsWith("pkg:"))
          .toSet
      case None => Set.empty
    }
  }

  /** Extract the canonical pURL from a JAR's metadata.
    *
    * Reads the gitoid Item's metadata and looks for the `CanonicalPurl` key in
    * the `extra` map.
    */
  private def extractCanonicalPurl(
      store: MemStorage,
      jarFile: File
  ): Option[String] = {
    val artifact = FileWrapper(jarFile, jarFile.getName, None)
    val (gitoid, _) = GitOIDUtils.computeAllHashes(artifact)

    store.read(gitoid).flatMap { item =>
      item.bodyAsItemMetaData.flatMap { meta =>
        meta.extra
          .get(MetadataKeyConstants.CANONICAL_PURL)
          .flatMap(_.headOption.map(_.value))
      }
    }
  }

  /** Parse a companion POM file to extract groupId/artifactId/version.
    *
    * Uses the production PomParser (same code Goat Rodeo uses), so the test
    * verifies the actual parsing behavior, not a test-only reimpl.
    */
  private def parseCompanionPom(pomFile: File): Option[ParsedPom] = {
    val content = Source.fromFile(pomFile).mkString
    PomParser.parse(content)
  }

  /** Assert Goat Rodeo finds at least as many packages as the reference
    * metadata scanner.
    *
    * Compares:
    *   1. pURL count: Goat Rodeo >= reference scanner 2. artifactId superset:
    *      Goat Rodeo's artifactIds must include all artifactIds the reference
    *      scanner found
    *
    * The groupId may differ — Goat Rodeo uses companion POM, the scanner may
    * use filename — but the artifactId should match. This verifies Goat Rodeo
    * discovers at least all the same packages.
    */
  private def assertMetadataParity(
      jarFile: File,
      goatPurls: Set[String]
  ): Unit = {
    MetadataGroundTruth.findEntry(metadataEntries, jarFile.getName).foreach {
      entry =>
        // Count check
        assert(
          goatPurls.size >= entry.purls.size,
          s"""Goat Rodeo found ${goatPurls.size} pURLs but reference metadata found ${entry.purls.size}.
           |
           |Goat Rodeo pURLs:
           |  ${goatPurls.toList.sorted.mkString("\n  ")}
           |
           |Reference metadata pURLs:
           |  ${entry.purls.sorted.mkString("\n  ")}
           |
           |JAR: ${jarFile.getAbsolutePath}
           |""".stripMargin
        )

        // ArtifactId superset check
        val goatArtifactIds = goatPurls.flatMap(PurlParts.artifactIdOf)
        val metadataArtifactIds =
          entry.purls.flatMap(PurlParts.artifactIdOf).toSet
        val missingArtifacts = metadataArtifactIds -- goatArtifactIds
        assert(
          missingArtifacts.isEmpty,
          s"""Goat Rodeo is missing ${missingArtifacts.size} artifactIds found by reference scanner.
           |
           |Missing artifactIds: ${missingArtifacts.toList.sorted
              .mkString(", ")}
           |Goat Rodeo artifactIds: ${goatArtifactIds.toList.sorted
              .mkString(", ")}
           |Reference artifactIds: ${metadataArtifactIds.toList.sorted
              .mkString(", ")}
           |
           |JAR: ${jarFile.getAbsolutePath}
           |""".stripMargin
        )
    }
  }

