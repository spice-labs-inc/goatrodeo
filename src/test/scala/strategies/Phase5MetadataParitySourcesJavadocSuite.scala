  // =========================================================================
  // Test 5.3: Sources JAR pURLs match embedded pom.properties
  // =========================================================================
  //
  // What it tests:
  //   For each sources JAR in the corpus (sampled), Goat Rodeo finds at
  //   least every pURL that can be derived from the JAR's embedded
  //   `pom.properties` files. All pURLs include `?packaging=sources`.
  //
  // Why it's relevant:
  //   This is the core metadata parity test for sources JARs. The
  //   reference scanner reads `META-INF/maven/*/pom.properties` in
  //   every JAR. Goat Rodeo must find at least the same pURLs (plus
  //   classifiers).
  //
  // Requirement section:
  //   REQ-5 — "Goat Rodeo pURLs must either match what the reference
  //   scanner finds or be better than what the reference scanner finds."
  //
  // Theory:
  //   For each sampled sources JAR:
  //   1. Extract expected pURLs by unzipping the JAR and reading all
  //      `META-INF/maven/*/pom.properties` files (at test time).
  //   2. Build expected pURL set: for each `pom.properties`, construct
  //      `pkg:maven/<groupId>/<artifactId>@<version>?packaging=sources`.
  //   3. Run Goat Rodeo on the JAR (directory-based setup).
  //   4. Assert Goat Rodeo's pURL set is a superset of expected pURLs
  //      (after normalizing — stripping qualifiers from Goat Rodeo pURLs
  //      for comparison, since Goat Rodeo adds `?packaging=sources` which
  //      the reference scanner doesn't).
  //   5. Assert ALL Goat Rodeo pURLs contain `?packaging=sources`.
  //   6. Assert Goat Rodeo pURL count <= expected count + 2 (tolerance for
  //      manifest-derived extras).

  // Sample 50 sources JARs deterministically (every Nth file)
  private val sampledSourcesJars: Vector[File] = {
    if (sourcesJars.isEmpty) Vector.empty
    else {
      val step = math.max(1, sourcesJars.length / 50)
      sourcesJars.indices.filter(_ % step == 0).map(sourcesJars(_)).toVector
    }
  }

  sampledSourcesJars.foreach { jarFile =>
    val props = extractPomProperties(jarFile)
    // Only test JARs that have at least 1 pom.properties entry
    if (props.nonEmpty) {
      test(
        s"Test 5.3: ${jarFile.getName} — pURLs match pom.properties (${props.size} entries)"
      ) {
        val expected = buildExpectedPurls(props, "packaging=sources")

        val store = processCorpusJar(jarFile)
        val goatPurls = extractGoatRodeoPurls(store, jarFile)

        // All Goat Rodeo pURLs must have ?packaging=sources (structured check)
        val withoutClassifier =
          goatPurls.filterNot(PurlParts.hasQualifier(_, "packaging", "sources"))
        assert(
          withoutClassifier.isEmpty,
          s"""pURLs without ?packaging=sources:
             |  ${withoutClassifier.toList.sorted.mkString("\n  ")}
             |
             |All pURLs: ${goatPurls.toList.sorted.mkString("\n  ")}
             |Expected (from pom.properties): ${expected.toList.sorted.mkString(
              "\n  "
            )}
             |JAR: ${jarFile.getAbsolutePath}
             |""".stripMargin
        )

        val normalizedGoat = goatPurls.map(PurlParts.normalize)
        val normalizedExpected = expected.map(PurlParts.normalize)

        // Goat Rodeo must find at least all expected pURLs (superset)
        val missing = normalizedExpected -- normalizedGoat
        assert(
          missing.isEmpty,
          s"""Goat Rodeo is missing ${missing.size} of ${expected.size} expected pURLs.
             |
             |Missing (in pom.properties but not in Goat Rodeo):
             |  ${missing.toList.sorted.mkString("\n  ")}
             |
             |Goat Rodeo pURLs:
             |  ${goatPurls.toList.sorted.mkString("\n  ")}
             |
             |JAR: ${jarFile.getAbsolutePath}
             |""".stripMargin
        )

        // Goat Rodeo pURL count should not be wildly inflated
        // (tolerance: +2 for manifest/embedded-pom-derived extras)
        assert(
          goatPurls.size <= expected.size + 2,
          s"""Goat Rodeo found ${goatPurls.size} pURLs but expected only ${expected.size}.
             |This suggests garbage pURLs or duplicate emission.
             |
             |Goat Rodeo pURLs:
             |  ${goatPurls.toList.sorted.mkString("\n  ")}
             |
             |JAR: ${jarFile.getAbsolutePath}
             |""".stripMargin
        )

        // Metadata ground truth parity: Goat Rodeo must find at least
        // as many packages as the reference scanner.
        assertMetadataParity(jarFile, goatPurls)
      }
    }
  }

